#!/usr/bin/env node
/**
 * Ordering.co brand adapter for the dashboard.
 *
 * The dashboard is a legacy styled-components app, so it does not run the
 * shadcn/Tailwind stack. It consumes the released brand tokens through this
 * adapter instead: an allowlist of `--od-*` CSS variables generated from the
 * canonical DTCG file, plus the Inter font, both pinned in
 * `brand/ordering-brand.lock.json` by release and sha256.
 *
 *   node scripts/brand-tokens.mjs check       offline: vendored files match the lock and the generated module
 *   node scripts/brand-tokens.mjs freshness   remote: the canonical files still match the lock
 *   node scripts/brand-tokens.mjs sync        remote: download, verify against the lock, regenerate
 *   node scripts/brand-tokens.mjs sync --accept   take a new release: rewrite the lock with the remote sha256
 *
 * A brand update is a reviewable change: run `sync --accept`, read the diff.
 */
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
export const LOCK_PATH = resolve(ROOT, 'brand/ordering-brand.lock.json')
export const TOKENS_PATH = resolve(ROOT, 'brand/ordering.tokens.json')
export const GENERATED_PATH = resolve(ROOT, 'src/@/components-dashboard/src/ui/src/styles/OrderingBrand/tokens.generated.js')

/** Tokens the dashboard uses. Anything else stays out until a surface needs it. */
export const ALLOWLIST = {
  root: [
    'font.family.sans',
    'font.weight.regular',
    'font.weight.medium',
    'font.weight.semibold',
    'font.size.1',
    'font.size.2',
    'font.size.3',
    'font.size.6',
    'font.lineHeight.heading',
    'font.lineHeight.body',
    'font.tracking.heading',
    'radius.control',
    'radius.component',
    'radius.panel',
    'stroke.default',
    'shadow.1',
    'shadow.2',
    'motion.duration.fast',
    'motion.duration.base',
    'space.2',
    'space.3',
    'space.4',
    'space.5',
    'space.6',
    'space.7'
  ],
  mode: [
    'semantic.background',
    'semantic.surface.default',
    'semantic.surface.subtle',
    'semantic.surface.strong',
    'semantic.text.default',
    'semantic.text.muted',
    'semantic.text.inverse',
    'semantic.border.default',
    'semantic.border.strong',
    'semantic.action.default',
    'semantic.action.foreground',
    'semantic.action.content',
    'semantic.action.hover',
    'semantic.action.soft',
    'semantic.action.focus',
    'semantic.state.danger.functional',
    'semantic.state.danger.soft'
  ]
}

export const sha256 = (buffer) => createHash('sha256').update(buffer).digest('hex')

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'))

const getPath = (tree, path) => path.split('.').reduce((node, key) => node?.[key], tree)

const resolveValue = (tree, value, seen = new Set()) => {
  const match = typeof value === 'string' && value.match(/^\{([^}]+)\}$/)
  if (!match) return value
  if (seen.has(match[1])) throw new Error(`Token reference loop at ${match[1]}`)
  seen.add(match[1])
  const target = getPath(tree, match[1])
  if (!target || target.$value === undefined) throw new Error(`Unresolved token reference ${match[1]}`)
  return resolveValue(tree, target.$value, seen)
}

const toCss = (value) => Array.isArray(value) ? `cubic-bezier(${value.join(', ')})` : String(value)

const readToken = (tree, path) => {
  const token = getPath(tree, path)
  const variable = token?.$extensions?.ordering?.cssVariable
  if (!token || token.$value === undefined || !variable) throw new Error(`Allowlisted token ${path} is missing or has no cssVariable`)
  return [variable, toCss(resolveValue(tree, token.$value))]
}

/** Builds the generated module source from the canonical token file. */
export const buildModule = (tokens, lock) => {
  const root = Object.fromEntries(ALLOWLIST.root.map(path => readToken(tokens, path)))
  const light = Object.fromEntries(ALLOWLIST.mode.map(path => readToken(tokens, `theme.light.${path}`)))
  const dark = Object.fromEntries(ALLOWLIST.mode.map(path => readToken(tokens, `theme.dark.${path}`)))
  const data = { release: lock.release, tokensSha256: lock.tokens.sha256, root, light, dark }
  return [
    '// Generated by scripts/brand-tokens.mjs from the released Ordering.co tokens.',
    '// Do not edit. Update with `pnpm brand:sync`; check with `pnpm brand:check`.',
    `export const ORDERING_BRAND = ${JSON.stringify(data, null, 2)}`,
    ''
  ].join('\n')
}

const fetchBuffer = async (url) => {
  const response = await fetch(url)
  if (!response.ok) throw new Error(`${url} answered ${response.status}`)
  return Buffer.from(await response.arrayBuffer())
}

/** Offline parity. Returns a list of problems; empty means in sync. */
export const checkOffline = () => {
  const problems = []
  const lock = readJson(LOCK_PATH)
  if (!existsSync(TOKENS_PATH)) return [`${TOKENS_PATH} is missing; run pnpm brand:sync`]
  const tokensBuffer = readFileSync(TOKENS_PATH)
  if (sha256(tokensBuffer) !== lock.tokens.sha256) problems.push('brand/ordering.tokens.json does not match the lock sha256')
  for (const [name, asset] of Object.entries(lock.assets)) {
    const path = resolve(ROOT, asset.path)
    if (!existsSync(path)) problems.push(`${name}: ${asset.path} is missing`)
    else if (sha256(readFileSync(path)) !== asset.sha256) problems.push(`${name}: ${asset.path} does not match the lock sha256`)
  }
  const expected = buildModule(JSON.parse(tokensBuffer.toString('utf8')), lock)
  const current = existsSync(GENERATED_PATH) ? readFileSync(GENERATED_PATH, 'utf8') : ''
  if (current !== expected) problems.push('tokens.generated.js is stale; run pnpm brand:sync')
  return problems
}

const freshness = async () => {
  const lock = readJson(LOCK_PATH)
  const stale = []
  const remoteTokens = sha256(await fetchBuffer(lock.tokens.url))
  if (remoteTokens !== lock.tokens.sha256) stale.push(`tokens: remote ${remoteTokens} ≠ lock ${lock.tokens.sha256}`)
  for (const [name, asset] of Object.entries(lock.assets)) {
    const remote = sha256(await fetchBuffer(asset.url))
    if (remote !== asset.sha256) stale.push(`${name}: remote ${remote} ≠ lock ${asset.sha256}`)
  }
  return stale
}

const sync = async ({ accept }) => {
  const lock = readJson(LOCK_PATH)
  const tokensBuffer = await fetchBuffer(lock.tokens.url)
  const tokensSha = sha256(tokensBuffer)
  if (tokensSha !== lock.tokens.sha256) {
    if (!accept) throw new Error(`Remote tokens sha256 ${tokensSha} ≠ lock. Re-run with --accept to take the new release.`)
    lock.tokens.sha256 = tokensSha
  }
  const tokens = JSON.parse(tokensBuffer.toString('utf8'))
  lock.tokens.version = tokens.version
  for (const [name, asset] of Object.entries(lock.assets)) {
    const buffer = await fetchBuffer(asset.url)
    const assetSha = sha256(buffer)
    if (assetSha !== asset.sha256) {
      if (!accept) throw new Error(`${name}: remote sha256 ${assetSha} ≠ lock. Re-run with --accept.`)
      asset.sha256 = assetSha
    }
    asset.bytes = buffer.length
    const path = resolve(ROOT, asset.path)
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, buffer)
  }
  mkdirSync(dirname(TOKENS_PATH), { recursive: true })
  writeFileSync(TOKENS_PATH, tokensBuffer)
  mkdirSync(dirname(GENERATED_PATH), { recursive: true })
  writeFileSync(GENERATED_PATH, buildModule(tokens, lock))
  writeFileSync(LOCK_PATH, `${JSON.stringify(lock, null, 2)}\n`)
}

const main = async () => {
  const [command, ...flags] = process.argv.slice(2)
  if (command === 'check') {
    const problems = checkOffline()
    if (problems.length) {
      console.error(problems.join('\n'))
      process.exit(1)
    }
    console.log('Ordering.co brand files match the lock.')
  } else if (command === 'freshness') {
    const stale = await freshness()
    if (stale.length) {
      console.error(`A newer brand release is published:\n${stale.join('\n')}\nRun pnpm brand:sync --accept and review the diff.`)
      process.exit(1)
    }
    console.log('The lock matches the published Ordering.co release.')
  } else if (command === 'sync') {
    await sync({ accept: flags.includes('--accept') })
    console.log('Ordering.co brand files synced. Review the diff before committing.')
  } else {
    console.error('Usage: node scripts/brand-tokens.mjs <check|freshness|sync [--accept]>')
    process.exit(2)
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch(error => {
    console.error(error.message)
    process.exit(1)
  })
}
