import { test, expect, fixtureUrl } from './fixtures'

test('populated UsersDeleteButton retains selection gate, cancel and password forwarding', async ({ page }) => {
  await page.goto(fixtureUrl('surface=admin-caller&mode=light'))
  const deletion = page.getByRole('button', { name: 'Delete', exact: true })
  await expect(deletion).toBeDisabled()
  await page.getByRole('button', { name: 'Toggle selected users' }).click()
  await deletion.click()
  const dialog = page.getByRole('dialog', { name: 'Confirm password', exact: true })
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(page.getByTestId('caller-requests')).toHaveText('[]')
  await expect(page.getByTestId('caller-deletions')).toHaveText('[]')
  await expect(deletion).toBeFocused()
  await deletion.click()
  await dialog.getByPlaceholder('Type your password to confirm.').fill('fixture-secret')
  await dialog.getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByTestId('caller-deletions')).toHaveText('[{"args":[null],"arity":1,"codeType":"undefined"}]')
})

test('populated UsersDeleteButton forwards the exact OTP string once', async ({ page }) => {
  await page.goto(fixtureUrl('surface=admin-caller&mode=dark'))
  await page.getByRole('button', { name: 'Toggle selected users' }).click()
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Confirm password', exact: true })
  await dialog.getByText('Email code', { exact: true }).click()
  await dialog.getByRole('button', { name: 'Get verify code', exact: true }).click()
  const alert = page.getByRole('alertdialog', { name: 'Ordering.co', exact: true })
  await alert.getByRole('button', { name: 'Close', exact: true }).click()
  for (let index = 0; index < 6; index++) await dialog.locator('.otp-input').nth(index).fill(String(index + 1))
  await expect(dialog).not.toBeVisible()
  await expect(page.getByTestId('caller-deletions')).toHaveText('[{"args":["123456"],"arity":1,"codeType":"string"}]')
})
